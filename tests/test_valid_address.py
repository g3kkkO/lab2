        ("192.168.1.1", True),
        ("10.0.0.1", True),
        ("8.8.8.8", True),
        ("172.16.254.1", True),
        ("255.255.255.255", True),
        ("0.0.0.1", True),
        ("1.0.0.0", True),
        ("0.255.0.255", True),
        ("99.199.9.9", True),
        ("100.200.250.255", True),
        ("256.0.0.1", False),
        ("1.256.0.0", False),
        ("1.1.256.0", False),
        ("1.1.1.256", False),
        ("999.999.999.999", False),
        ("192.168.300.1", False),
